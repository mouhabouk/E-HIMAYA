from datetime import datetime
from typing import Any

from pgvector.sqlalchemy import Vector
from sqlalchemy import Computed, DateTime, SmallInteger, Text, func
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column

from app.core.db import Base


class ProcedureChunk(Base):
    """One passage (``## `` section) of a procedure sheet of docs/procedures, the assistant's retrieval unit."""

    __tablename__ = "procedure_chunk"
    __table_args__ = {"schema": "decision"}

    # "<procedure_id>.<lang>#<position>", e.g. "flood.fr#2".
    id: Mapped[str] = mapped_column(Text, primary_key=True)
    procedure_id: Mapped[str] = mapped_column(Text)
    lang: Mapped[str] = mapped_column(Text)
    title: Mapped[str] = mapped_column(Text)
    heading: Mapped[str] = mapped_column(Text)
    body: Mapped[str] = mapped_column(Text)
    position: Mapped[int] = mapped_column(SmallInteger)
    categories: Mapped[list[str]] = mapped_column(ARRAY(Text), server_default="{}")
    classifications: Mapped[list[str]] = mapped_column(ARRAY(Text), server_default="{}")
    # [{"label": "...", "url": "https://..."}]
    sources: Mapped[list[dict[str, Any]]] = mapped_column(JSONB, server_default="[]")
    path: Mapped[str] = mapped_column(Text)
    checksum: Mapped[str] = mapped_column(Text)
    # Generated by PostgreSQL (full-text fallback when no embedding is available).
    search: Mapped[Any] = mapped_column(
        TSVECTOR, Computed("to_tsvector('simple'::regconfig, title || ' ' || heading || ' ' || body)"), deferred=True
    )
    embedding: Mapped[list[float] | None] = mapped_column(Vector(768), deferred=True)
    embedding_model: Mapped[str | None] = mapped_column(Text)
    indexed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
