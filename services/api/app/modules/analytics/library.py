"""Reports repository and scheduled reports (docs/api/phase-8-contract.md §1, FR-C-21).

A document is queued here and generated by the worker loop "analytics" (app/modules/analytics/worker.py); its file is
downloaded through a short-lived pre-signed URL (302), every download audited. A regional staff member creates and sees
the documents of their own gouvernorat only; national documents (``gouvernorats`` empty) are for national roles.
"""

