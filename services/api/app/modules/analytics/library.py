async def _schedule(
    session: AsyncSession, principal: Principal, schedule_id: uuid.UUID, lock: bool = False
) -> Schedule:
    query = select(Schedule).where(Schedule.id == schedule_id, _visible(Schedule.gouvernorats, principal))
    row = await session.scalar(query.with_for_update() if lock else query)
    if row is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "not_found")
    return row


@router.get("/report-schedules/{schedule_id}", response_model=schemas.ScheduleOut)
async def get_schedule(principal: Scheduler, session: Session, schedule_id: uuid.UUID) -> schemas.ScheduleOut:
    return schedule_out(await _schedule(session, principal, schedule_id))


@router.patch("/report-schedules/{schedule_id}", response_model=schemas.ScheduleOut)
async def update_schedule(
    principal: Scheduler, session: Session, schedule_id: uuid.UUID, body: schemas.SchedulePatch
) -> schemas.ScheduleOut:
    row = await _schedule(session, principal, schedule_id, lock=True)
    changes = body.model_dump(exclude_unset=True, mode="json")
    if body.title is not None:
        row.title = body.title
    if body.filters is not None:
        row.filters = _schedule_filters(body.filters)
    if body.gouvernorats is not None:
        row.gouvernorats = service.resolve_scope(principal, body.gouvernorats)
    if body.format is not None:
        row.format = body.format
    if body.lang is not None:
        row.lang = body.lang
    if body.recipients is not None:
        row.recipients = _recipients(body.recipients)
    if body.enabled is not None:
        row.enabled = body.enabled
    now = datetime.now(UTC)
    if body.cron is not None:
        row.at_time, row.weekday, row.day = _cron(body.cron)
        row.frequency = body.cron.frequency
    if body.cron is not None or body.enabled:
        row.next_run_at = domain.next_run(row.frequency, row.at_time, row.weekday, row.day, now)
    row.updated_at = now
    await audit.record(
        session,
        actor=audit.actor_of(principal),
        action="analytics.schedule.update",
        target=f"analytics_schedule:{row.id}",
        details={"changes": changes},
    )
    await session.flush()
    await session.refresh(row)
    out = schedule_out(row)
    await session.commit()
    return out


@router.delete("/report-schedules/{schedule_id}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_schedule(principal: Scheduler, session: Session, schedule_id: uuid.UUID) -> None:
    """Delete a schedule; the documents it produced stay in the repository."""
    row = await _schedule(session, principal, schedule_id, lock=True)
    await audit.record(
        session,
        actor=audit.actor_of(principal),
        action="analytics.schedule.delete",
        target=f"analytics_schedule:{row.id}",
        details={"kind": row.kind, "title": row.title},
    )
    await session.delete(row)
    await session.commit()
