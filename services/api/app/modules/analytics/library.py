from datetime import UTC, date, datetime, time
from typing import Annotated, Any, Literal

import structlog
from fastapi import APIRouter, Depends, Header, HTTPException, Query, Response, status
from fastapi.responses import RedirectResponse
from sqlalchemy import String, and_, any_, cast, func, or_, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core import ratelimit
from app.core.config import get_settings
from app.core.db import get_session, get_sessionmaker
from app.core.security import Principal, require_roles
from app.core.storage import get_store
from app.modules.analytics import domain, schemas, service
from app.modules.analytics.models import Report, Scenario, Schedule
from app.modules.audit import service as audit
from app.modules.ops.models import Incident
from app.modules.reports.models import Media

log = structlog.get_logger()
router = APIRouter(prefix="/api/v1/staff", tags=["staff", "reports-library"])
Session = Annotated[AsyncSession, Depends(get_session)]
Reader = Annotated[Principal, Depends(require_roles(*domain.READ_ROLES))]
Planner = Annotated[Principal, Depends(require_roles(*domain.PLANNER_ROLES))]
Scheduler = Annotated[Principal, Depends(require_roles(*domain.SCHEDULE_ROLES))]
HOUR_S = 3600
REPORTS_PER_HOUR = 30
DOWNLOAD_TTL_S = 300


def _visible(column: Any, principal: Principal) -> Any:
    """Rows whose gouvernorats ([] = national) are within the caller's scope."""
    if principal.is_national:
        return True
    return and_(func.cardinality(column) > 0, column.contained_by([principal.gouvernorat_code]))


def _page_filter(model: Any, cursor: str | None) -> Any:
    if not cursor:
        return True
    at, raw_id = service.decode_cursor(cursor)
    try:
        item_id = uuid.UUID(raw_id)
    except ValueError as exc:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "invalid_cursor") from exc
    return or_(model.created_at < at, and_(model.created_at == at, model.id < item_id))


# ---------------------------------------------------------------- reports repository


def report_out(report: Report) -> schemas.ReportOut:
    return schemas.ReportOut.model_validate(report, from_attributes=True)


async def _check_targets(
    session: AsyncSession, principal: Principal, kind: str, filters: schemas.ReportFilters, codes: list[int]
) -> list[int]:
    """Incident and scenario documents: the target must exist and be in scope; the document takes its gouvernorats."""
    if kind in domain.INCIDENT_KINDS:
        if filters.incident_id is None:
            raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "incident_required")
        incident = await session.get(Incident, filters.incident_id)
        if incident is None:
            raise HTTPException(status.HTTP_404_NOT_FOUND, "not_found")
        if incident.gouvernorat_code is None:
            if not principal.is_national:
                raise HTTPException(status.HTTP_403_FORBIDDEN, "out_of_scope")
            return []
        if not principal.can_access_gouvernorat(incident.gouvernorat_code):
            raise HTTPException(status.HTTP_403_FORBIDDEN, "out_of_scope")
        return [incident.gouvernorat_code]
    if kind == "scenario":
        if filters.scenario_id is None:
            raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "scenario_required")
        scenario = await session.get(Scenario, filters.scenario_id)
        if scenario is None or not service.in_scope(principal, list(scenario.gouvernorats)):
            raise HTTPException(status.HTTP_404_NOT_FOUND, "not_found")
        return list(scenario.gouvernorats)
    if filters.incident_id is not None or filters.scenario_id is not None:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "invalid_filters")
    return service.resolve_scope(principal, codes)


def _check_period(start: date, end: date) -> None:
    if end < start:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "invalid_period")
    if (end - start).days + 1 > get_settings().analytics_max_period_days:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "period_too_long")


@router.post("/reports-library", response_model=schemas.ReportOut, status_code=status.HTTP_202_ACCEPTED)
async def create_report(principal: Planner, session: Session, body: schemas.ReportIn) -> schemas.ReportOut:
    """Queue a document (generated by the worker; the creator is notified in the app when it is ready)."""
    await ratelimit.enforce(f"an-rep:{principal.subject}", REPORTS_PER_HOUR, HOUR_S)
    _check_period(body.period_from, body.period_to)
    codes = await _check_targets(session, principal, body.kind, body.filters, body.gouvernorats)
    report = Report(
        kind=body.kind,
        title=body.title,
        lang=body.lang,
        period_from=body.period_from,
        period_to=body.period_to,
        gouvernorats=codes,
        filters=body.filters.model_dump(mode="json", exclude_none=True),
        format=body.format,
        creator_scope=principal.gouvernorat_code,
        created_by=audit.actor_of(principal),
    )
    session.add(report)
    await session.flush()
    await audit.record(
        session,
        actor=audit.actor_of(principal),
        action="analytics.report.create",
        target=f"analytics_report:{report.id}",
        details={"kind": report.kind, "format": report.format, "gouvernorats": codes, "filters": report.filters},
    )
    await session.refresh(report)
    out = report_out(report)
    await session.commit()
    return out


async def _knowledge_ids(principal: Principal, q: str) -> list[uuid.UUID] | None:
    """Ids of matching documents from the events library index (phase 8 knowledge module), None when unavailable."""
    try:
        from app.modules.knowledge.search import search_ids  # type: ignore[import-not-found,unused-ignore]
    except ImportError:
        return None
    try:
        # Own session: a failed index query must not abort the transaction of the repository query.
        async with get_sessionmaker()() as own:
            ids: list[uuid.UUID] | None = await search_ids(own, principal, q, kinds=["report_doc"])
    except Exception:  # the index is an accelerator: its failure never breaks the repository search
        log.warning("analytics.knowledge_search_failed", exc_info=True)
        return None
    return ids


def _like(q: str) -> str:
    return "%" + q.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_") + "%"


@router.get("/reports-library", response_model=schemas.ReportPage)
async def library(
    principal: Reader,
    session: Session,
    q: Annotated[str | None, Query(max_length=200)] = None,
    kind: domain.ReportKind | None = None,
    from_: Annotated[date | None, Query(alias="from")] = None,
    to: date | None = None,
    gouvernorat: Annotated[int | None, Query(ge=1, le=99)] = None,
    status_: Annotated[str | None, Query(alias="status", pattern="^(queued|running|ready|failed)$")] = None,
    cursor: str | None = None,
    limit: Annotated[int, Query(ge=1, le=100)] = 30,
) -> schemas.ReportPage:
    """Search and filter: ``q`` matches the title and the filters (and the full text of the events library index
    when the knowledge module is available); ``from``/``to`` select documents whose period overlaps them."""
    query = select(Report).where(_visible(Report.gouvernorats, principal), _page_filter(Report, cursor))
    backend: Literal["knowledge", "postgres"] | None = None
    if q and q.strip():
        text_match = or_(
            Report.title.ilike(_like(q.strip()), escape="\\"),
            cast(Report.filters, String).ilike(_like(q.strip()), escape="\\"),
        )
        ids = await _knowledge_ids(principal, q.strip())
        backend = "postgres" if ids is None else "knowledge"
        query = query.where(text_match if ids is None else or_(text_match, Report.id.in_(ids)))
    if kind:
        query = query.where(Report.kind == kind)
    if from_:
        query = query.where(Report.period_to >= from_)
    if to:
        query = query.where(Report.period_from <= to)
    if gouvernorat is not None:
        if not principal.can_access_gouvernorat(gouvernorat):
            raise HTTPException(status.HTTP_403_FORBIDDEN, "out_of_scope")
        query = query.where(any_(Report.gouvernorats) == gouvernorat)
    if status_:
        query = query.where(Report.status == status_)
    rows = list(await session.scalars(query.order_by(Report.created_at.desc(), Report.id.desc()).limit(limit)))
    next_cursor = service.encode_cursor(rows[-1].created_at, rows[-1].id) if len(rows) == limit else None
    return schemas.ReportPage(
        items=[report_out(r) for r in rows],
        next_cursor=next_cursor,
        search_backend=backend,
    )


async def _report(session: AsyncSession, principal: Principal, report_id: uuid.UUID) -> Report:
    report = await session.scalar(
        select(Report).where(Report.id == report_id, _visible(Report.gouvernorats, principal))
    )
    if report is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "not_found")
    return report


@router.get("/reports-library/{report_id}", response_model=schemas.ReportOut)
async def get_report(principal: Reader, session: Session, report_id: uuid.UUID) -> schemas.ReportOut:
    return report_out(await _report(session, principal, report_id))


@router.get("/reports-library/{report_id}/download", response_model=None)
async def download(
    principal: Reader,
    session: Session,
    report_id: uuid.UUID,
    accept: Annotated[str | None, Header()] = None,
) -> Response | schemas.DownloadOut:
    """302 to a short-lived pre-signed URL of the file (``Accept: application/json``: the URL as JSON instead)."""
    report = await _report(session, principal, report_id)
    if report.status != "ready" or report.media_id is None:
        raise HTTPException(status.HTTP_409_CONFLICT, "report_not_ready")
    media = await session.get(Media, report.media_id)
    if media is None:
        raise HTTPException(status.HTTP_409_CONFLICT, "report_not_ready")
    filename = f"ehimaya-{report.kind}-{report.period_from.isoformat()}-{str(report.id)[:8]}.{report.format}"
    url = get_store().presign_get(
        media.object_key,
        expires_s=DOWNLOAD_TTL_S,
        content_type=domain.CONTENT_TYPES[report.format],
        disposition=f'attachment; filename="{filename}"',
    )
    await audit.record(
        session,
        actor=audit.actor_of(principal),
        action="analytics.report.download",
        target=f"analytics_report:{report.id}",
        details={"sha256": report.sha256, "format": report.format},
    )
    await session.commit()
    if accept and "application/json" in accept:
        return schemas.DownloadOut(url=url)
    return RedirectResponse(url, status_code=status.HTTP_302_FOUND, headers={"Cache-Control": "no-store"})


# ---------------------------------------------------------------- scheduled reports


def schedule_out(row: Schedule) -> schemas.ScheduleOut:
    return schemas.ScheduleOut(
        id=row.id,
        kind=row.kind,
        title=row.title,
        filters=row.filters,
        gouvernorats=list(row.gouvernorats),
        format=row.format,
        lang=row.lang,
        cron=schemas.Cron(
            frequency=row.frequency,
            time=row.at_time.strftime("%H:%M"),
            weekday=row.weekday,
            day=row.day,
        ),
        recipients=list(row.recipients),
        enabled=row.enabled,
        last_run_at=row.last_run_at,
        next_run_at=row.next_run_at,
        last_report_id=row.last_report_id,
        created_by=row.created_by,
        created_at=row.created_at,
        updated_at=row.updated_at,
    )


def _cron(cron: schemas.Cron) -> tuple[time, int | None, int | None]:
    if not cron.valid():
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "invalid_cron")
    hour, minute = (int(v) for v in cron.time.split(":"))
    return time(hour, minute), cron.weekday, cron.day


def _recipients(raw: list[str]) -> list[str]:
    cleaned = schemas.valid_subjects(raw)
    if cleaned is None:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "invalid_recipients")
    return cleaned


def _schedule_filters(filters: schemas.ReportFilters) -> dict[str, Any]:
    if filters.incident_id is not None or filters.scenario_id is not None:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "invalid_filters")
    return filters.model_dump(mode="json", exclude_none=True)


@router.post("/report-schedules", response_model=schemas.ScheduleOut, status_code=status.HTTP_201_CREATED)
async def create_schedule(principal: Scheduler, session: Session, body: schemas.ScheduleIn) -> schemas.ScheduleOut:
    at, weekday, day = _cron(body.cron)
    codes = service.resolve_scope(principal, body.gouvernorats)
    now = datetime.now(UTC)
    row = Schedule(
        kind=body.kind,
        title=body.title,
        filters=_schedule_filters(body.filters),
        gouvernorats=codes,
        format=body.format,
        lang=body.lang,
        frequency=body.cron.frequency,
        at_time=at,
        weekday=weekday,
        day=day,
        recipients=_recipients(body.recipients),
        enabled=body.enabled,
        next_run_at=domain.next_run(body.cron.frequency, at, weekday, day, now),
        creator_scope=principal.gouvernorat_code,
        created_by=audit.actor_of(principal),
    )
    session.add(row)
    await session.flush()
    await audit.record(
        session,
        actor=audit.actor_of(principal),
        action="analytics.schedule.create",
        target=f"analytics_schedule:{row.id}",
        details={"kind": row.kind, "cron": body.cron.model_dump(), "gouvernorats": codes, "recipients": row.recipients},
    )
    await session.refresh(row)
    out = schedule_out(row)
    await session.commit()
    return out


