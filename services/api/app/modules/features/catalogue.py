"""The catalogue of what the system administrator grants and hides (L4, docs/phase-l/design-l4.md §8).

Every page of the dashboard, and under it its tabs and buttons, with the API routes each one guards. A route is
``METHOD /path`` relative to ``/api/v1/staff`` (``WRITE`` = any method but GET, ``*`` = any method). A page owns its
routes by prefix (the longest prefix wins); a tab or a button owns its routes exactly.

Flags (the fixed ceiling, Yamen 2026-10-28: the security rules stay a ceiling nobody lifts):

* ``personal``: shows reporters, callers, victims, citizens or personnel; never granted to a governor or a minister.
* ``national``: needs the national scope; never granted to a regional account or to a role in one gouvernorat.
* ``dormant``: held by nobody by default; a route under it is refused until the administrator grants it (L5a, the
  dry run). Its buttons are dormant with it.
* ``safety``: a button never hidden nor dormant (the stop of a dry run); its handler checks who may press it.
* ``fixed``: never granted at all (sensitive layers, the paid basemap key, accounts, the audit, break-glass, the
  permissions themselves). It can still be hidden.

``act_as`` is the role a grantee acts as on the routes of the feature (and only there); left out, it is taken from
the roles the routes require (``registry``).
"""

from dataclasses import dataclass, field
from typing import Literal

from app.core.security import Role

# «system» (2026-11-13): one of the 20 systems of the menu (menu.json), a level above its pages.
Kind = Literal["page", "tab", "button", "system"]
Names = tuple[str, str, str]  # ar, fr, en


@dataclass(frozen=True)
class Spec:
    key: str
    kind: Kind
    names: Names
    routes: tuple[str, ...] = ()
    flags: frozenset[str] = frozenset()
    act_as: Role | None = None
    # The dashboard path of a page or of a tab shown in the menu.
    nav: str | None = None
    group: str | None = None
    children: tuple["Spec", ...] = field(default=())


def page(
    key: str,
    group: str,
    nav: str,
    names: Names,
    routes: tuple[str, ...] = (),
    *children: Spec,
    flags: str = "",
    act_as: Role | None = None,
) -> Spec:
    # A page of the field app, the citizen app or the portal has no dashboard path (phase 5).
    return Spec(key, "page", names, routes, frozenset(flags.split()), act_as, nav or None, group, children)


def tab(
    key: str, names: Names, *routes: str, flags: str = "", act_as: Role | None = None, nav: str | None = None
) -> Spec:
    return Spec(key, "tab", names, routes, frozenset(flags.split()), act_as, nav)


def button(key: str, names: Names, *routes: str, flags: str = "", act_as: Role | None = None) -> Spec:
    return Spec(key, "button", names, routes, frozenset(flags.split()), act_as)


