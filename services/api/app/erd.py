"""``python -m app.erd [path] [--check]``: write the entity-relationship diagram of the models (phase 10 §6.2).

One Mermaid ``erDiagram`` per schema in ``docs/erd.md``, with primary keys, foreign keys and the relations (a foreign
key to another schema is drawn in the referencing schema). Stable output, checked for drift in CI like OpenAPI.
"""

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

from sqlalchemy import Table

from app.core.db import Base
from app.modules import models as _models  # noqa: F401  (registers every table)

DEFAULT = Path(__file__).resolve().parents[3] / "docs" / "erd.md"


def _entity(table: Table) -> str:
    return f"{table.schema}__{table.name}" if table.schema else table.name


def _type(column_type: object) -> str:
    try:
        name = str(column_type)
    except Exception:  # types without a generic compilation (e.g. some dialect types)
        name = type(column_type).__name__
    return re.sub(r"[^a-z0-9_]", "_", name.lower()).strip("_") or "value"


def render() -> str:
    by_schema: dict[str, list[Table]] = defaultdict(list)
    for table in Base.metadata.sorted_tables:
        by_schema[table.schema or "public"].append(table)
    out = [
        "# Entity-relationship diagram",
        "",
        "Generated by `python -m app.erd` from the SQLAlchemy models (phase 10 §6.2); do not edit by hand.",
        "Entities are named `<schema>__<table>`. A foreign key to another schema is drawn in the referencing schema.",
        "",
    ]
    for schema in sorted(by_schema):
        tables = sorted(by_schema[schema], key=lambda t: t.name)
        out += [f"## {schema}", "", "```mermaid", "erDiagram"]
        relations: list[str] = []
        for table in tables:
            out.append(f"    {_entity(table)} {{")
            for column in table.columns:
                keys = [k for k, on in (("PK", column.primary_key), ("FK", bool(column.foreign_keys))) if on]
                out.append(f"        {_type(column.type)} {column.name}{' ' + ','.join(keys) if keys else ''}")
            out.append("    }")
            for fk in sorted(table.foreign_key_constraints, key=lambda c: (c.referred_table.fullname, c.name or "")):
                columns = ", ".join(c.name for c in fk.columns)
                relations.append(f'    {_entity(fk.referred_table)} ||--o{{ {_entity(table)} : "{columns}"')
        out += sorted(set(relations))
        out += ["```", ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(prog="python -m app.erd")
    parser.add_argument("path", nargs="?", type=Path, default=DEFAULT)
    parser.add_argument("--check", action="store_true", help="exit 1 when the file differs from the models")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = args.path.read_text(encoding="utf-8") if args.path.exists() else ""
        if current != text:
            print(f"{args.path} is out of date: run `python -m app.erd`", file=sys.stderr)
            return 1
        return 0
    args.path.write_text(text, encoding="utf-8")
    print(f"wrote {args.path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
