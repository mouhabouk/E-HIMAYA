#!/usr/bin/env python3
"""Requirement → test traceability (phase 10 §6.3, R20).

Reads the requirement identifiers of docs/01-requirements.html (the "id" cell of each requirement row) and the
identifiers cited in the tests (comments such as ``# covers: FR-A-022``, docstrings, test names), then writes
docs/traceability.md: each requirement with the test files citing it, and the list of requirements no test cites.
The gaps are listed, not hidden. ``--check`` exits 1 when the committed file is not current (CI).
"""

import argparse
import html
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REQUIREMENTS = ROOT / "docs" / "01-requirements.html"
OUTPUT = ROOT / "docs" / "traceability.md"
ID = r"(?:FR-[A-Z]-\d{3}|NFR-\d{2}|BR-\d{2}|UC-\d{2})"
ROW = re.compile(
    rf'<td class="id">(?P<id>{ID})</td>\s*<td>(?P<text>.*?)</td>\s*(?:<td>(?P<prio>.*?)</td>)?', re.S
)
CITED = re.compile(rf"\b{ID}\b")
# Test sources: every suite of the repository (Python, TypeScript, Dart) and the infrastructure checks.
TEST_GLOBS = (
    "services/*/tests/**/*.py",
    "apps/dashboard/src/**/*.test.ts",
    "apps/dashboard/src/**/*.test.tsx",
    "apps/dashboard/e2e/**/*.ts",
    "apps/portal/src/**/*.test.ts",
    "apps/portal/src/**/*.test.tsx",
    "apps/mobile/test/**/*.dart",
    "apps/mobile/integration_test/**/*.dart",
    "infra/**/check_*.py",
    "infra/**/*.test.yml",
    "infra/backup/drill.sh",
    "infra/smoke/**/*",
)


def _clean(fragment: str | None) -> str:
    return html.unescape(re.sub(r"<[^>]+>", "", fragment or "")).strip()


def requirements() -> list[tuple[str, str, str]]:
    """(id, text, priority or category). FR rows: id, text, priority; NFR rows: id, category, text; business rules
    are list items; use cases are headings."""
    source = REQUIREMENTS.read_text(encoding="utf-8")
    rows: dict[str, tuple[str, str, str]] = {}
    for m in ROW.finditer(source):
        first, second = _clean(m["text"]), _clean(m["prio"])
        if m["id"].startswith("NFR-"):
            rows.setdefault(m["id"], (m["id"], second, first))
        else:
            rows.setdefault(m["id"], (m["id"], first, second))
    for m in re.finditer(rf'<(?P<tag>li|p)><span class="id">(?P<id>{ID})</span>(?P<text>.*?)</(?P=tag)>', source, re.S):
        rows.setdefault(m["id"], (m["id"], _clean(m["text"]), "rule"))
    for m in re.finditer(rf"<h4>(?P<id>UC-\d{{2}})(?P<text>.*?)</h4>", source, re.S):
        rows.setdefault(m["id"], (m["id"], _clean(m["text"]), "use case"))
    return sorted(rows.values(), key=lambda r: _order(r[0]))


def _order(rid: str) -> tuple[str, int, str]:
    kind, *rest = rid.split("-")
    return (kind, int(rest[-1]), "-".join(rest[:-1]))


def citations() -> dict[str, set[str]]:
    cited: dict[str, set[str]] = defaultdict(set)
    seen: set[Path] = set()
    for pattern in TEST_GLOBS:
        for path in sorted(ROOT.glob(pattern)):
            if not path.is_file() or path in seen or "node_modules" in path.parts:
                continue
            seen.add(path)
            try:
                text = path.read_text(encoding="utf-8")
            except UnicodeDecodeError:
                continue
            for rid in set(CITED.findall(text)):
                cited[rid].add(path.relative_to(ROOT).as_posix())
    return cited


def _short(text: str, n: int = 110) -> str:
    text = " ".join(text.split()).replace("|", "\\|")
    return text if len(text) <= n else text[: n - 1].rstrip() + "…"


def render() -> str:
    reqs = requirements()
    cited = citations()
    covered = [r for r in reqs if r[0] in cited]
    missing = [r for r in reqs if r[0] not in cited]
    out = [
        "# Requirement traceability",
        "",
        "Generated by `scripts/traceability.py` from `docs/01-requirements.html` and the identifiers cited in the",
        "tests (`# covers: FR-…` comments, docstrings, names). Do not edit by hand. A requirement listed under",
        '"Not cited by any test" may still be implemented: it means no test names it yet.',
        "",
        f"* Requirements: {len(reqs)}",
        f"* Cited by at least one test: {len(covered)}",
        f"* Not cited by any test: {len(missing)}",
        "",
        "## Requirement → tests",
        "",
        "| Id | Priority / kind | Requirement | Tests |",
        "|---|---|---|---|",
    ]
    for rid, text, prio in covered:
        files = "<br>".join(f"`{f}`" for f in sorted(cited[rid]))
        out.append(f"| {rid} | {prio} | {_short(text)} | {files} |")
    out += ["", "## Not cited by any test", "", "| Id | Priority / kind | Requirement |", "|---|---|---|"]
    out += [f"| {rid} | {prio} | {_short(text)} |" for rid, text, prio in missing]
    unknown = sorted(set(cited) - {r[0] for r in reqs}, key=_order)
    if unknown:
        out += ["", "## Identifiers cited by tests but absent from the requirements", ""]
        out += [f"* {rid}: " + ", ".join(f"`{f}`" for f in sorted(cited[rid])) for rid in unknown]
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(prog="scripts/traceability.py")
    parser.add_argument("--check", action="store_true", help="exit 1 when docs/traceability.md is not current")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print("docs/traceability.md is out of date: run scripts/traceability.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
